_FEATURED_CODES = ("tr", "en", "de", "fr", "es", "it", "pt", "ru", "ar")
_LANGUAGE_NAMES = dict(WHISPER_LANGUAGES)


def language_options() -> list[tuple[str, str]]:
    """Return auto-detect followed by the commonly used languages and all others."""
    featured = [code for code in _FEATURED_CODES if code in _LANGUAGE_NAMES]
    remaining = sorted(
        (code for code, _name in WHISPER_LANGUAGES if code not in _FEATURED_CODES),
        key=lambda code: _LANGUAGE_NAMES[code].casefold(),
    )
    ordered_codes = featured + remaining
    return [("", "Otomatik algıla")] + [
        (_LANGUAGE_NAMES[code], code) for code in ordered_codes
    ]
